PX = 100
names = {c: ('space' if c == ' ' else 'uni%04X' % ord(c)) for c in G}
order = ['.notdef'] + [names[c] for c in G]
glyphs, metrics = {}, {}
def build(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        y_top = (7 - r) * PX
        x = 0
        while x < len(row):
            if row[x] == '#':
                s = x
                while x < len(row) and row[x] == '#': x += 1
                x0, x1, y0, y1 = s*PX, x*PX, y_top-PX, y_top
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
            else:
                x += 1
    return pen.glyph()
glyphs['.notdef'] = build(["#####","#...#","#...#","#...#","#...#","#...#","#####"])
metrics['.notdef'] = (600, 0)
for c, spec in G.items():
    rows = spec.split('|')
    assert all(len(r) == 5 for r in rows), (c, rows)
    g = build(rows); glyphs[names[c]] = g
    metrics[names[c]] = (600, 0)
fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap({ord(c): names[c] for c in G})
fb.setupGlyf(glyphs)
for n in order:
    g = glyphs[n]; g.recalcBounds(fb.font['glyf']) if hasattr(g, 'recalcBounds') else None
fb.setupHorizontalMetrics({n: (600, getattr(glyphs[n], 'xMin', 0) or 0) for n in order})
fb.setupHorizontalHeader(ascent=800, descent=-200)
fb.setupNameTable({'familyName': 'Delve', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=800, usWinDescent=200, fsSelection=0x40)
fb.setupPost(isFixedPitch=1)
buf = io.BytesIO(); fb.save(buf)
data = buf.getvalue()
open('/home/claude/delve.ttf', 'wb').write(data)
sys.stdout.write(base64.b64encode(data).decode())
